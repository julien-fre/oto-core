"""Sortie TypeScript : un module par connecteur, et l'index.

Un module porte des définitions structurelles typées (`ts/src/types.ts`), sans
rien exécuter : le paquet d'un hôte les adapte à son contrat de fonction et
exécute la requête avec son client HTTP, son coffre et son journal. Le module ne
dépend que de `./types`.

Le schéma d'entrée est le JSON Schema (2020-12) de la description, recopié tel
quel après résolution des ancres YAML : l'hôte le valide avec un validateur JSON
Schema standard. La fabrique n'en vérifie qu'une chose, que la racine est un objet
strict (`type: object`, `additionalProperties: false`) ; sinon la fonction n'est
pas générée, et elle est nommée avec sa raison.
"""
from __future__ import annotations

import copy
import json
from dataclasses import dataclass, field
from typing import Any

from .descriptions import DEFAULT_TIMEOUT_S, PATH_PARAM, Description, act

HEADER = "// Generated by the fabrique from {source}. Do not edit: run `python -m fabrique`."
GENERATED_MARK = "// Generated by the fabrique"
PAGINATION_ARGUMENTS = ("all_pages", "max_pages")
RESERVED = {
    "break", "case", "catch", "class", "const", "continue", "debugger", "default", "delete", "do", "else", "enum",
    "export", "extends", "false", "finally", "for", "function", "if", "import", "in", "instanceof", "new", "null",
    "return", "super", "switch", "this", "throw", "true", "try", "typeof", "var", "void", "while", "with", "yield",
    "let", "static", "implements", "interface", "package", "private", "protected", "public", "await", "connector",
}


class NotGenerated(ValueError):
    """Une fonction que la fabrique ne génère pas : la raison est nommée en tête du module."""


def js(value: Any) -> str:
    """Un littéral JavaScript : JSON en est un sous-ensemble."""
    return json.dumps(value, ensure_ascii=False)


WIDTH = 110


def js_block(value: Any, indent: int) -> str:
    """Un littéral JavaScript aligné sur `indent` niveaux : sur une ligne s'il tient dans `WIDTH`, sinon une clé par ligne."""
    flat = js(value)
    if not isinstance(value, (dict, list)) or not value or len(flat) + 2 * indent <= WIDTH:
        return flat
    pad = "  " * (indent + 1)
    if isinstance(value, dict):
        rows = [f"{pad}{js(key)}: {js_block(item, indent + 1)}" for key, item in value.items()]
        return "{\n" + ",\n".join(rows) + "\n" + "  " * indent + "}"
    rows = [pad + js_block(item, indent + 1) for item in value]
    return "[\n" + ",\n".join(rows) + "\n" + "  " * indent + "]"


@dataclass
class Skipped:
    function: str
    reason: str


@dataclass
class Module:
    connector: str
    identifier: str
    source: str
    generated: list[str] = field(default_factory=list)
    skipped: list[Skipped] = field(default_factory=list)


def camel(name: str) -> str:
    head, *rest = name.split("_")
    return head + "".join(part[:1].upper() + part[1:] for part in rest)


def _served_input(function: dict) -> dict:
    """L'entrée servie : celle de la description, plus `all_pages` et `max_pages` quand la fonction pagine."""
    served = copy.deepcopy(function["input"])
    if served.get("type") != "object" or served.get("additionalProperties") is not False:
        raise NotGenerated("input: the root must be a strict object (type: object, additionalProperties: false)")
    pagination = function.get("pagination")
    if not pagination:
        return served
    taken = [name for name in PAGINATION_ARGUMENTS if name in served["properties"]]
    if taken:
        raise NotGenerated(f"input declares {', '.join(taken)}, which pagination adds")
    limit = pagination["max_pages"]
    served["properties"]["all_pages"] = {
        "type": "boolean",
        "description": f"Read the following pages too, up to max_pages (at most {limit}).",
    }
    served["properties"]["max_pages"] = {
        "type": "integer", "minimum": 1, "maximum": limit, "default": limit,
        "description": "Pages read when all_pages is true.",
    }
    return served


def _object(entries: list[tuple[str, str]], indent: int) -> str:
    """Un objet littéral, une clé par ligne ; les valeurs sont déjà des expressions."""
    if not entries:
        return "{}"
    pad = "  " * (indent + 1)
    body = "\n".join(f"{pad}{key}: {value}," for key, value in entries)
    return "{\n" + body + "\n" + "  " * indent + "}"


def _request(call: dict) -> str:
    entries = [
        ("method", js(call["method"])),
        ("path", js(call["path"])),
        ("pathParams", js(PATH_PARAM.findall(call["path"]))),
        ("query", js(call.get("query") or {})),
        ("body", js(call.get("body") or {})),
        ("headers", js(call.get("headers") or {})),
    ]
    if "files" in call:
        entries.append(("files", js(call["files"])))
    if "constants" in call:
        entries.append(("constants", js(call["constants"])))
    if "encode" in call:
        entries.append(("encode", js(call["encode"])))
    return _object(entries, 1)


def _pagination(pagination: dict) -> str:
    entries = [
        ("kind", js(pagination["kind"])),
        ("requestParam", js(pagination["request_param"])),
        ("next", js(pagination["next"])),
    ]
    if "more" in pagination:
        entries.append(("more", js(pagination["more"])))
    if "total" in pagination:
        entries.append(("total", js(pagination["total"])))
    entries.append(("maxPages", js(pagination["max_pages"])))
    return "{ " + ", ".join(f"{k}: {v}" for k, v in entries) + " }"


def _list(items: list[str], indent: int) -> str:
    if not items:
        return "[]"
    pad = "  " * (indent + 1)
    return "[\n" + "\n".join(f"{pad}{item}," for item in items) + "\n" + "  " * indent + "]"


def function_source(connector: str, function: dict) -> str:
    """La définition d'une fonction, ou `NotGenerated`."""
    if "handwritten" in function:
        raise NotGenerated("handwritten: the fabrique does not generate it")
    qualified = f"{connector}.{function['name']}"
    schema = js_block(_served_input(function), 1)
    examples = [
        "{ title: " + js(example["title"]) + ", input: " + js(example["input"]) + " }"
        for example in function["examples"]
    ]
    refusals = [
        "{ code: " + js(r["code"]) + ", when: " + js(r["when"]) + ", message: " + js(r["message"]) + _signal(r) + " }"
        for r in function.get("refusals", [])
    ]
    entries = [
        ("name", js(qualified)),
        ("connector", js(connector)),
        ("class", js(function["class"])),
        ("act", js(act(function))),
    ]
    if "scopes" in function:
        entries.append(("scopes", js(function["scopes"])))
    entries += [
        ("description", js(function["description"].strip())),
        ("schema", schema),
        ("examples", _list(examples, 1)),
        ("refusals", _list(refusals, 1)),
    ]
    if "checks" in function:
        entries.append(("checks", _list([_check(c) for c in function["checks"]], 1)))
    if "expect" in function:
        entries.append(("expect", _list([_check(c) for c in function["expect"]], 1)))
    entries.append(("request", _request(function["call"])))
    if "timeout_s" in function:
        entries.append(("timeoutMs", js(function["timeout_s"] * 1000)))
    if "async" in function:
        entries.append(("async", _async(connector, function["async"])))
    if "pagination" in function:
        entries.append(("pagination", _pagination(function["pagination"])))
    if "output" in function:
        output = function["output"]
        out = [(key, js(output[key])) for key in ("items", "strip", "projection") if key in output]
        if "schema" in output:
            out.append(("schema", js(output["schema"])))
        entries.append(("output", "{ " + ", ".join(f"{k}: {v}" for k, v in out) + " }"))
    if "cost" in function:
        entries.append(("cost", _cost(function["cost"])))
    if "confirm" in function:
        entries.append(("confirm", "{ summary: " + js(function["confirm"]["summary"]) + " }"))
    return f"export const {camel(function['name'])} = defineFunction({_object(entries, 0)})\n"


def _cost(cost: dict) -> str:
    """Le coût d'une fonction, ses clés dans l'ordre du format, seulement celles qu'elle déclare."""
    parts = [f"{key}: {js(cost[key])}" for key in ("per", "items", "times") if key in cost]
    if "weights" in cost:
        parts.append("weights: { field: " + js(cost["weights"]["field"]) + ", values: " + js(cost["weights"]["values"]) + " }")
    if "unit" in cost:
        parts.append(f"unit: {js(cost['unit'])}")
    if "settle" in cost:
        parts.append("settle: { path: " + js(cost["settle"]["path"]) + " }")
    return "{ " + ", ".join(parts) + " }"


def collection_fields(connector: str, declared: dict) -> dict:
    """La relève dans les noms de la sortie : `collect` qualifiée comme la sonde, `within_s` en millisecondes
    (`withinMs`), `no_deadline` en `noDeadline`. Sert la définition d'une fonction (`async`) et les attendus des cas du
    coût (`fabrique.cases`), pour qu'une seule conversion les tienne."""
    fields: dict = {"collect": f"{connector}.{declared['collect']}"}
    if "within_s" in declared:
        fields["withinMs"] = declared["within_s"] * 1000
    if declared.get("no_deadline") is True:
        fields["noDeadline"] = True
    return fields


def _async(connector: str, declared: dict) -> str:
    """Le travail asynchrone : la relève qualifiée, l'identifiant du travail, le délai en millisecondes."""
    job = declared["job_id"]
    fields = collection_fields(connector, declared)
    parts = ["collect: " + js(fields["collect"]), "jobId: { from: " + js(job["from"]) + ", to: " + js(job["to"]) + " }"]
    parts += [f"{key}: {js(fields[key])}" for key in ("withinMs", "noDeadline") if key in fields]
    return "{ " + ", ".join(parts) + " }"


def _check(check: dict) -> str:
    return "{ " + ", ".join(f"{key}: {js(value)}" for key, value in check.items()) + " }"


def _auth(connector: str, auth: dict) -> str:
    """Les clés du format en camelCase ; les valeurs telles quelles (noms côté API, adresses, noms des niveaux
    d'accès et droits), sauf l'identité lue par une fonction, qualifiée comme la sonde, et les clés de `exchange`."""
    entries = {}
    for key, value in auth.items():
        if key == "identity" and "function" in value:
            value = {"function": f"{connector}.{value['function']}", "path": value["path"]}
        elif key == "exchange":
            value = {camel(k): v for k, v in value.items()}
        entries[camel(key)] = value
    return js_block(entries, 1)


def _credential_field(field: dict) -> dict:
    """Un champ du credential, `holder` toujours dit (`account` par défaut)."""
    return {"name": field["name"], "label": field["label"], "secret": field["secret"], "holder": field.get("holder", "account")}


def _signal(entry: dict) -> str:
    """Le signal de refus du service d'une entrée de la table ou d'un refus : sa condition sur le corps et la marque du
    compte, quand elle les déclare."""
    parts = []
    if "body" in entry:
        parts.append(", body: " + js(entry["body"]))
    if "marks_account" in entry:
        parts.append(", marksAccount: " + js(entry["marks_account"]))
    return "".join(parts)


def _errors(errors: list[dict]) -> str:
    rows = [
        "{ status: " + js(e["status"]) + ", code: " + js(e["code"]) + ", message: " + js(e["message"])
        + ", retryable: " + js(e["retryable"]) + _signal(e) + " }"
        for e in errors
    ]
    return _list(rows, 1)


def connector_module(description: Description, source: str | None = None) -> Module:
    """Le module d'un connecteur ; `source`, le fichier que nomme son en-tête (sa description par défaut)."""
    data = description.data
    connector = data["connector"]
    name = connector["name"]
    module = Module(connector=name, identifier=camel(name), source="")
    blocks = []
    exported = []
    for function in data["functions"]:
        qualified = f"{name}.{function['name']}"
        identifier = camel(function["name"])
        if identifier in RESERVED:
            raise NotGenerated(f"{qualified}: {identifier!r} cannot be an exported name")
        try:
            blocks.append(function_source(name, function))
        except NotGenerated as refusal:
            module.skipped.append(Skipped(qualified, str(refusal)))
            continue
        module.generated.append(qualified)
        exported.append(identifier)

    entries = [
        ("name", js(name)),
        ("label", js(connector["label"])),
        ("namespace", js(connector["namespace"])),
        ("version", js(connector["version"])),
        ("apiVersion", js(connector["api_version"])),
    ]
    if "base_url" in connector:
        entries.append(("baseUrl", js(connector["base_url"])))
    if "base_urls" in connector:
        entries.append(("baseUrls", js(connector["base_urls"])))
    entries.append(("auth", _auth(name, connector["auth"])))
    entries.append(("credential", js([_credential_field(f) for f in connector.get("credential", [])])))
    if "account_identity" in connector:
        entries.append(("accountIdentity", js(connector["account_identity"])))
    if "settings" in connector:
        entries.append(("settings", js_block(connector["settings"], 1)))
    entries.append(("modes", js(connector["modes"])))
    entries.append(("timeoutMs", js(connector.get("timeout_s", DEFAULT_TIMEOUT_S) * 1000)))
    if "query_arrays" in connector:
        entries.append(("queryArrays", js(connector["query_arrays"])))
    if "headers" in connector:
        entries.append(("headers", js(connector["headers"])))
    if "rate_limit" in connector:
        rate = connector["rate_limit"]
        entries.append(("rateLimit", "{ requests: " + js(rate["requests"]) + ", intervalMs: " + js(rate["seconds"] * 1000) + " }"))
    if "quota" in connector:
        entries.append(("quota", js(connector["quota"])))
    entries.append(("errors", _errors(connector["errors"])))
    if "probe" in connector:
        probe = connector["probe"]
        balance = probe.get("balance")
        reads = "" if balance is None else (
            ", balance: { path: " + js(balance["path"]) + ", min: " + js(balance["min"]) + ", unit: " + js(balance["unit"]) + " }")
        entries.append(("probe", "{ function: " + js(f"{name}.{probe['function']}") + ", nonEmpty: " + js(probe.get("non_empty", [])) + reads + " }"))
    if "exposure" in data:
        entries.append(("exposure", js(data["exposure"])))
    entries.append(("functions", _list(exported, 1)))

    head = [HEADER.format(source=source or f"connectors/{name}/connector.yaml")]
    if module.skipped:
        head.append("// Not generated:")
        head += [f"// - {s.function}: {s.reason}" for s in module.skipped]
    head += ['import { defineConnector, defineFunction } from "./types"', ""]
    footer = f"export const connector = defineConnector({_object(entries, 0)})\n"
    module.source = "\n".join(head) + "\n" + "\n".join(blocks) + ("\n" if blocks else "") + footer
    return module


def index_source(modules: list[Module]) -> str:
    lines = [HEADER.format(source="connectors/*/connector.yaml")]
    lines += [f'import * as {m.identifier} from "./{m.connector}"' for m in modules]
    lines.append('import type { Connector } from "./types"')
    lines.append("")
    lines += [f"export {{ {m.identifier} }}" for m in modules]
    lines.append('export type * from "./types"')
    lines.append('export * from "./adapters/index"')
    lines.append("")
    lines.append("/** Every generated connector, in name order; each module keeps its precise types. */")
    lines.append("export const connectors: readonly Connector[] = " + _list([f"{m.identifier}.connector" for m in modules], 0))
    return "\n".join(lines) + "\n"
