"""Sortie Python servie : les descriptions telles qu'un hôte les sert, dans la distribution de la lib.

Les fichiers YAML ne partent pas dans la distribution PyPI (`pyproject.toml`) ; un hôte Python qui sert les fonctions
décrites (le lecteur générique d'oto 1) les lit dans des modules générés, `oto/connectors/descriptions/` : un module par
connecteur, `<nom>.py`, qui porte `DESCRIPTION`, chargé à la demande, et `__init__.py`, qui porte `NAMES` et
`load(nom)`. Chaque module porte la description contrôlée par la fabrique, sans `output.sample` : l'exemple de réponse
est une garde de la fabrique (règle 19), jamais un contrat. `call` y reste : le moteur Python
(`oto/connectors/engine/`) en compose la requête. Chaque `input` y est l'entrée servie, celle de la sortie TypeScript
(`all_pages` et `max_pages` ajoutés à une fonction qui pagine). Les fonctions pures qui les lisent sont dans
`oto/connectors/serve.py`, le moteur qui les exécute dans `oto/connectors/engine/`. `python -m fabrique --check`
échoue quand un module commité ne suit plus sa description, ou qu'un module ne correspond plus à aucune.
"""
from __future__ import annotations

import copy
import pprint

from .descriptions import REPO, Description, DescriptionError
from .typescript import NotGenerated, served_input

OUTPUT = REPO / "oto" / "connectors" / "descriptions"
RELATIVE = "oto/connectors/descriptions"
GENERATED_MARK = "# Generated by the fabrique from connectors/*/connector.yaml. Do not edit: run `python -m fabrique`.\n"


def served(description: Description) -> dict:
    """La description servie : sans `output.sample`, l'entrée de chaque fonction telle qu'elle est servie, `call` gardé."""
    data = copy.deepcopy(description.data)
    for function in data["functions"]:
        try:
            function["input"] = served_input(function)
        except NotGenerated as refused:
            raise DescriptionError(f"{description.name}: function {function['name']}: not served: {refused}") from refused
        output = function.get("output")
        if output is not None:
            output.pop("sample", None)
    return data


def _module_source(description: Description) -> str:
    body = pprint.pformat(served(description), width=110, sort_dicts=False)
    return (
        GENERATED_MARK
        + f'"""The `{description.name}` description as a host serves it: without `output.sample`, '
        + 'each `input` as served, `call` kept for the engine (`oto.connectors.descriptions.load`)."""\n'
        + "DESCRIPTION = "
        + body
        + "\n"
    )


_INDEX = '''"""The descriptions as a host serves them, one module per connector, loaded on demand (`load`).

`NAMES` lists the described connectors; `load(name)` returns the description of one, as the fabrique checked it, without
`output.sample`, each `input` as served, `call` kept. The functions of `oto.connectors.serve` read it, the engine
(`oto.connectors.engine`) runs it.
"""
from __future__ import annotations

import importlib

NAMES = {names}


def load(name: str) -> dict:
    """The served description of `name`; `KeyError` naming it when no connector of that name is described."""
    if name not in NAMES:
        raise KeyError(f"no described connector {{name!r}}")
    return importlib.import_module(f"{{__name__}}.{{name}}").DESCRIPTION
'''


def files(descriptions: list[Description]) -> dict[str, str]:
    """Par nom de fichier sous `oto/connectors/descriptions/`, sa source : un module par description, puis l'index."""
    out = {f"{d.name}.py": _module_source(d) for d in descriptions}
    names = pprint.pformat(tuple(d.name for d in descriptions), width=110 - len("NAMES = "))
    out["__init__.py"] = GENERATED_MARK + _INDEX.format(names=names.replace("\n", "\n" + " " * len("NAMES = ")))
    return out
