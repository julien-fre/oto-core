"""Sortie Python de données : le coût et le travail asynchrone de chaque fonction décrite.

Un module généré, `oto/connectors/declared.py`, porte, par connecteur et par fonction, le `cost` et l'`async` que la
fabrique a contrôlés (et le `max_pages` d'une lecture paginée qui coûte, que son pire cas lit), dans les noms de la
description. Les fonctions pures de `oto/connectors/cost.py` le lisent avec la sémantique d'oto-core (`costOf`,
`settledQuantity`, `collectionOf`). Une seule source : la lib ne relit aucun fichier YAML à l'exécution, et
`python -m fabrique --check` échoue quand le module commité ne suit plus les descriptions.
"""
from __future__ import annotations

import pprint

from .descriptions import REPO, Description

OUTPUT = REPO / "oto" / "connectors" / "declared.py"
RELATIVE = "oto/connectors/declared.py"
GENERATED_MARK = "# Generated by the fabrique from connectors/*/connector.yaml. Do not edit: run `python -m fabrique`.\n"


def _entry(function: dict) -> dict:
    entry: dict = {}
    if "cost" in function:
        entry["cost"] = function["cost"]
        if "pagination" in function:
            entry["pagination"] = {"max_pages": function["pagination"]["max_pages"]}
    if "async" in function:
        entry["async"] = function["async"]
    return entry


def declared(descriptions: list[Description]) -> dict[str, dict[str, dict]]:
    """Par connecteur, par fonction qui déclare un coût ou un travail asynchrone : ce qu'elle déclare."""
    table: dict[str, dict[str, dict]] = {}
    for description in descriptions:
        functions = {f["name"]: _entry(f) for f in description.data["functions"] if "cost" in f or "async" in f}
        if functions:
            table[description.name] = functions
    return table


def python_source(descriptions: list[Description]) -> str:
    body = pprint.pformat(declared(descriptions), width=110, sort_dicts=False)
    return (
        GENERATED_MARK
        + '"""Cost and asynchronous job of each described function, as the fabrique checked them (`oto.connectors.cost` reads them)."""\n'
        + "DECLARED = "
        + body
        + "\n"
    )
