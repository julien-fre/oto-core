"""Sortie Python de données : le coût, le travail asynchrone et le fichier rendu de chaque fonction décrite.

Un module généré, `oto/connectors/declared.py`, porte, par connecteur et par fonction, le `cost` et l'`async` que la
fabrique a contrôlés (et le `max_pages` d'une lecture paginée qui coûte, que son pire cas lit), dans les noms de la
description. Les fonctions pures de `oto/connectors/cost.py` le lisent avec la sémantique d'oto-core (`costOf`,
`settledQuantity`, `collectionOf`). Une fonction qui rend un fichier y porte aussi son `output.file`, défauts résolus,
et son délai en secondes (`timeout_s`, le sien ou celui du connecteur), que lit `oto/connectors/files.py`. Une seule
source : la lib ne relit aucun fichier YAML à l'exécution, et `python -m fabrique --check` échoue quand le module commité
ne suit plus les descriptions.
"""
from __future__ import annotations

import pprint

from .descriptions import DEFAULT_TIMEOUT_S, REPO, Description, output_file

OUTPUT = REPO / "oto" / "connectors" / "declared.py"
RELATIVE = "oto/connectors/declared.py"
GENERATED_MARK = "# Generated by the fabrique from connectors/*/connector.yaml. Do not edit: run `python -m fabrique`.\n"


def _entry(connector: dict, function: dict) -> dict:
    entry: dict = {}
    if "cost" in function:
        entry["cost"] = function["cost"]
        if "pagination" in function:
            entry["pagination"] = {"max_pages": function["pagination"]["max_pages"]}
    if "async" in function:
        entry["async"] = function["async"]
    file = output_file(function)
    if file is not None:
        entry["file"] = file
        entry["timeout_s"] = function.get("timeout_s", connector.get("timeout_s", DEFAULT_TIMEOUT_S))
    return entry


def declared(descriptions: list[Description]) -> dict[str, dict[str, dict]]:
    """Par connecteur, par fonction qui déclare un coût, un travail asynchrone ou un fichier rendu : ce qu'elle déclare."""
    table: dict[str, dict[str, dict]] = {}
    for description in descriptions:
        connector = description.data["connector"]
        functions = {f["name"]: _entry(connector, f) for f in description.data["functions"]
                     if "cost" in f or "async" in f or output_file(f) is not None}
        if functions:
            table[description.name] = functions
    return table


def python_source(descriptions: list[Description]) -> str:
    body = pprint.pformat(declared(descriptions), width=110, sort_dicts=False)
    return (
        GENERATED_MARK
        + '"""Cost, asynchronous job and rendered file of each described function, as the fabrique checked them '
        + '(`oto.connectors.cost` and `oto.connectors.files` read them)."""\n'
        + "DECLARED = "
        + body
        + "\n"
    )
