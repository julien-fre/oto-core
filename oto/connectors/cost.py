"""What a call of a described function costs, in pure functions.

They read `oto.connectors.declared`, generated by the fabrique from the descriptions (never a YAML file at run time),
with the semantics of the format (docs/conception/format-de-description.md, « Coût d'un appel », « Travail
asynchrone ») and of the oto 2 host package (`costOf`, `settledQuantity`, `collectionOf`):

- `worst_case`: before the call, from its validated arguments ;
- `settled_quantity`: after a successful call, from its JSON answers (those of its collect function for an asynchronous
  job that settles) ;
- `collection_of`: the collect call of a submitted job.

Nothing is reserved, settled nor collected here; no I/O.
"""
from __future__ import annotations

import math
from typing import Any

from .declared import DECLARED


class CostError(ValueError):
    """A cost that cannot be computed: arguments the schema did not validate, a submission without its job id."""


def _declared(connector: str, function: str) -> dict:
    try:
        return DECLARED[connector][function]
    except KeyError:
        return {}


def _is_number(value: Any) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _finite(value: Any) -> bool:
    """A number that a double holds finite, as the host package reads JSON: an integer beyond the range of a double
    (JavaScript reads Infinity) is not, where `math.isfinite` would raise `OverflowError`."""
    if not _is_number(value):
        return False
    try:
        return math.isfinite(value)
    except OverflowError:
        return False


def value_at(value: Any, path: str) -> Any:
    """The value at a dotted path, a list index as digits; `None` when absent."""
    current = value
    for segment in path.split("."):
        if isinstance(current, dict):
            current = current.get(segment)
        elif isinstance(current, list) and segment.isdigit():
            index = int(segment)
            current = current[index] if index < len(current) else None
        else:
            return None
    return current


def _unit(cost: dict) -> str:
    if "unit" in cost:
        return cost["unit"]
    return "pages" if cost["per"] == "page" else "requests"


def _qualified(connector: str, function: str) -> str:
    return f"{connector}.{function}"


def _list(name: str, args: dict, argument: str) -> list:
    value = args.get(argument)
    if not isinstance(value, list) or not value:
        raise CostError(f"{name}: cost argument {argument} is not a non-empty list: validate the arguments against the schema first.")
    return value


def _page_count(entry: dict, args: dict) -> int:
    pagination = entry.get("pagination")
    if pagination is None or args.get("all_pages") is not True:
        return 1
    wanted = args["max_pages"] if _is_number(args.get("max_pages")) else pagination["max_pages"]
    return max(1, min(wanted, pagination["max_pages"]))


def _weighted(name: str, cost: dict, args: dict) -> int:
    field, values = cost["weights"]["field"], cost["weights"]["values"]
    total = 0
    for element in _list(name, args, cost["items"]):
        listed = element.get(field) if isinstance(element, dict) else None
        if not isinstance(listed, list) or not listed:
            raise CostError(f"{name}: each element of {cost['items']} lists its {field}: validate the arguments against the schema first.")
        for value in listed:
            if not isinstance(value, str) or value not in values:
                raise CostError(f"{name}: {field} value {value!r} has no weight: validate the arguments against the schema first.")
            total += values[value]
    return total


def worst_case(connector: str, function: str, args: dict) -> dict | None:
    """`{quantity, unit}` before the call: request and page, the requests it may send; item, the size of items times
    that of times (one without), or the sum of the weights of the values each item lists. `None` without a cost."""
    cost = _declared(connector, function).get("cost")
    if cost is None:
        return None
    name = _qualified(connector, function)
    if cost["per"] != "item":
        return {"quantity": _page_count(_declared(connector, function), args), "unit": _unit(cost)}
    if "weights" in cost:
        return {"quantity": _weighted(name, cost, args), "unit": _unit(cost)}
    times = len(_list(name, args, cost["times"])) if "times" in cost else 1
    return {"quantity": len(_list(name, args, cost["items"])) * times, "unit": _unit(cost)}


def settled_quantity(connector: str, function: str, args: dict, answers: list) -> dict | None:
    """`{quantity, unit, from, exceeded}` after a successful call. With settle, the first finite number of zero or more
    (a finite double, as the host reads JSON) at its path in `answers` (`from: response`), else the worst case
    (`from: unreadable`); without settle, the requests sent (`requests`) or, per item, the worst case (`worst_case`).
    `exceeded`: a quantity read above the worst case, settled as is and to be reported. `None` without a cost."""
    worst = worst_case(connector, function, args)
    if worst is None:
        return None
    cost = _declared(connector, function)["cost"]
    if "settle" in cost:
        path = cost["settle"]["path"]
        read = next((v for v in (value_at(a, path) for a in answers) if _finite(v) and v >= 0), None)
        if read is None:
            return {**worst, "from": "unreadable", "exceeded": False}
        return {"quantity": read, "unit": worst["unit"], "from": "response", "exceeded": read > worst["quantity"]}
    if cost["per"] == "item":
        return {**worst, "from": "worst_case", "exceeded": False}
    if not answers:
        raise CostError(f"{_qualified(connector, function)}: a settled call has at least one response.")
    return {"quantity": len(answers), "unit": worst["unit"], "from": "requests", "exceeded": False}


def collection_of(connector: str, function: str, answer: Any) -> dict | None:
    """`{function, args, within_s, no_deadline}`: the collect call of the job read in the submission's answer.
    `None` for a function that is not asynchronous."""
    job = _declared(connector, function).get("async")
    if job is None:
        return None
    job_id = value_at(answer, job["job_id"]["from"])
    if not ((isinstance(job_id, str) and job_id) or _finite(job_id)):
        raise CostError(f"{_qualified(connector, function)}: the submission answered without its job id at {job['job_id']['from']}.")
    return {
        "function": _qualified(connector, job["collect"]),
        "args": {job["job_id"]["to"]: job_id},
        "within_s": job.get("within_s"),
        "no_deadline": job.get("no_deadline") is True,
    }
