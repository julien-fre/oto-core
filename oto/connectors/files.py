"""The file a described function renders (`output.file`), read from the answer of its call.

A client sends the call to the API, handles its refusals as usual, then hands the successful answer to `file_output`,
which reads the declaration in `oto.connectors.declared` (generated by the fabrique, never a YAML file at run time) and
applies the semantics of the format (docs/conception/format-de-description.md, « Un fichier rendu ») and of the oto 2
host package:

- `body`: the body of the answer, read as a stream under `max_bytes` (a `Content-Length` beyond refuses before reading);
- `url`: the address the JSON answer holds at `path`, guarded (`https`, public address, no credentials), downloaded
  without following any redirect, with no authentication (`auth: none`) or, under `auth: account`, by the client's
  session, to the origin of `base_url` only;
- `base64`, `base64url`: the field at `path`, decoded strictly;

then the name (header, field, template: the first with a declared extension) and the type (that of the extension; an
announced type that is not one of its types, nor generic, nor absent, refuses). The timeout of the function holds end to
end, as a deadline counted while reading. A refusal raises `FileOutputError`, whose code is one of the six named
refusals common to both sides (connectors/_cases/file.yaml); no message, exception or log ever carries the address of
the third party, which is a bearer token. Nothing is kept here: the consumer stores the `FileOut` where it wants. The
lib reads no secret: the authenticated session is the one the client built from what its consumer gave it.
"""
from __future__ import annotations

import base64
import binascii
import json
import re
import time
import unicodedata
from dataclasses import dataclass
from typing import Any, Mapping, Optional
from urllib.parse import unquote, urlsplit

import requests
from urllib3.exceptions import ReadTimeoutError

from ..tools.common.url_guard import assert_public_https_url
from .cost import value_at
from .declared import DECLARED

# The largest file, the ceiling of a file at the host of oto 2 (50 MB).
MAX_BYTES = 52_428_800
# The largest JSON answer that carries an address: that of an ordinary JSON answer at the host of oto 2 (4 MB).
JSON_LIMIT = 4 * 1024 * 1024
CHUNK = 64 * 1024
GENERIC_TYPES = ("application/octet-stream", "binary/octet-stream")
NAME_LENGTH = 255
REFUSALS = ("file_download_refused", "file_foreign_origin", "file_missing", "file_too_large", "file_type_refused",
            "file_unreadable")
DEFAULT_PORTS = {"https": 443, "http": 80}

_TEMPLATE_ARGUMENT = re.compile(r"\{([^{}]*)\}")
_DISPOSITION_PARAMETER = re.compile(r";\s*([!#$%&'*+.^_`|~0-9A-Za-z-]+)\s*=\s*(\"(?:[^\"\\]|\\.)*\"|[^;]*)")
_EXTENDED_VALUE = re.compile(r"^([A-Za-z0-9!#$%&+^_`{}~-]+)'[^']*'(.*)$")
_BASE64 = re.compile(r"^[A-Za-z0-9+/]*={0,2}$")
_BASE64URL = re.compile(r"^[A-Za-z0-9_-]*={0,2}$")


@dataclass(frozen=True)
class FileOut:
    """A rendered file: its name, its bytes in memory (50 MB at most), its MIME type, that of its extension."""

    name: str
    content: bytes
    mime: str

    def __post_init__(self) -> None:
        if not isinstance(self.content, bytes):
            raise TypeError("FileOut.content holds bytes")
        if len(self.content) > MAX_BYTES:
            raise ValueError(f"FileOut.content holds at most {MAX_BYTES} bytes")


class FileOutputError(Exception):
    """A refused file, nothing kept: `code` is one of the six named refusals; the message never carries an address."""

    def __init__(self, code: str, message: str):
        if code not in REFUSALS:
            raise ValueError(f"unknown file refusal {code!r}")
        super().__init__(f"{code}: {message}")
        self.code = code
        self.message = message


class _Deadline:
    """The timeout of the function, counted from the start of `file_output` while reading."""

    def __init__(self, seconds: float):
        self.seconds = seconds
        self.at = time.monotonic() + seconds

    def remaining(self) -> float:
        left = self.at - time.monotonic()
        if left <= 0:
            raise self.exceeded()
        return left

    def exceeded(self) -> requests.Timeout:
        return requests.Timeout(f"the file was not read within the timeout of the function ({self.seconds:g} s)")


def file_output(connector: str, function: str, *, answer: requests.Response, args: Mapping[str, Any],
                session: requests.Session, base_url: str) -> FileOut:
    """The file that `connector.function` renders, from the successful `answer` of its call.

    `args` are the arguments of the call (the name template cites them); `session` is the client's authenticated
    session, used to download an address only under `auth: account` and to the origin of `base_url`, the resolved base
    URL of the API. Raises `FileOutputError` on a refusal, `requests.Timeout` past the timeout of the function,
    `LookupError` for a function that declares no file, `ValueError` for an answer that is not a success."""
    entry = DECLARED.get(connector, {}).get(function, {})
    if "file" not in entry:
        raise LookupError(f"{connector}.{function} declares no output.file")
    if not 200 <= answer.status_code < 300:
        raise ValueError("file_output needs a successful answer: the client handles the refusals of the API first")
    file = entry["file"]
    deadline = _Deadline(entry["timeout_s"])
    source = file["from"]
    if source == "body":
        return _from_response(file, args, answer, None, deadline)
    data = _json_answer(answer, source, file["max_bytes"], deadline)
    if source == "url":
        return _from_url(file, args, data, session, base_url, deadline)
    return _from_base64(file, args, data, source)


# --- Sources -------------------------------------------------------------------------------------------------------


def _from_response(file: dict, args: Mapping[str, Any], response: requests.Response, data: Any,
                   deadline: _Deadline) -> FileOut:
    """The bytes of a response (the answer, or the download of an address), named and typed from its headers."""
    name, extension = _name(file, args, response.headers, data)
    mime = _mime(file, extension, response.headers.get("Content-Type"))
    content = _read(response, file["max_bytes"], deadline, "file_too_large", f"the file is over {file['max_bytes']} bytes")
    if not content:
        raise FileOutputError("file_missing", "the third party sent an empty file")
    return FileOut(name=name, content=content, mime=mime)


def _from_url(file: dict, args: Mapping[str, Any], data: Any, session: requests.Session, base_url: str,
              deadline: _Deadline) -> FileOut:
    address = _field(data, file["path"], "address")
    account = file["auth"] == "account"
    if account and not _same_origin(address, base_url):
        raise FileOutputError("file_foreign_origin", "the third party gave a file address outside its API; nothing was downloaded")
    guarded = True
    try:
        assert_public_https_url(address)
    except ValueError:
        guarded = False
    if not guarded:
        raise FileOutputError("file_download_refused", "the file address is not a public https address without credentials")
    transport = session if account else _bare(session, address)
    timeout = deadline.remaining()
    response, timed_out = None, False
    try:
        response = transport.get(address, stream=True, allow_redirects=False, timeout=timeout)
    except requests.Timeout:
        timed_out = True
    except requests.RequestException:
        pass
    if timed_out:
        raise deadline.exceeded()
    if response is None:
        raise FileOutputError("file_download_refused", "the download of the file failed")
    if not 200 <= response.status_code < 300:
        status = response.status_code
        response.close()
        raise FileOutputError("file_download_refused", f"the third party refused the download (HTTP {status})"
                              + ("; redirects are not followed" if 300 <= status < 400 else "")
                              + "; the address may have expired: call the function again")
    try:
        return _from_response(file, args, response, data, deadline)
    finally:
        response.close()


def _from_base64(file: dict, args: Mapping[str, Any], data: Any, source: str) -> FileOut:
    encoded = _field(data, file["path"], "file field")
    content = _decode(encoded, source)
    if content is None:
        raise FileOutputError("file_unreadable", f"the third party sent a file field that is not valid {source}")
    if len(content) > file["max_bytes"]:
        raise FileOutputError("file_too_large", f"the file is over {file['max_bytes']} bytes")
    name, extension = _name(file, args, None, data)
    return FileOut(name=name, content=content, mime=file["types"][extension][0])


# --- Reading -------------------------------------------------------------------------------------------------------


def _json_answer(answer: requests.Response, source: str, max_bytes: int, deadline: _Deadline) -> Any:
    """The JSON answer that holds an address (4 MB at most) or the encoded bytes (up to the encoded size of
    `max_bytes`, beyond the JSON around them)."""
    if source == "url":
        body = _read(answer, JSON_LIMIT, deadline, "file_unreadable", "the answer that holds the file address is over 4 MB")
    else:
        limit = 4 * -(-max_bytes // 3) + JSON_LIMIT
        body = _read(answer, limit, deadline, "file_too_large", f"the file is over {max_bytes} bytes")
    parsed, readable = None, True
    try:
        parsed = json.loads(body)
    except ValueError:
        readable = False
    if not readable:
        raise FileOutputError("file_unreadable", "the answer that holds the file is not JSON")
    return parsed


def _read(response: requests.Response, limit: int, deadline: _Deadline, over: str, message: str) -> bytes:
    """The body of `response`, refused before reading when its `Content-Length` passes `limit`, otherwise stopped at the
    first byte too many; the deadline is checked at each chunk."""
    declared = response.headers.get("Content-Length", "").strip()
    if declared.isdigit() and int(declared) > limit:
        response.close()
        raise FileOutputError(over, message)
    chunks, size = [], 0
    iterator = response.iter_content(CHUNK)
    broken = timed_out = False
    while True:
        deadline.remaining()
        try:
            chunk = next(iterator)
        except StopIteration:
            break
        except requests.RequestException as error:
            timed_out = isinstance(error, requests.Timeout) or any(isinstance(a, ReadTimeoutError) for a in error.args)
            broken = True
            break
        size += len(chunk)
        if size > limit:
            response.close()
            raise FileOutputError(over, message)
        chunks.append(chunk)
    if timed_out:
        raise deadline.exceeded()
    if broken:
        raise FileOutputError("file_download_refused", "the transfer of the file broke off")
    return b"".join(chunks)


def _field(data: Any, path: str, what: str) -> str:
    value = value_at(data, path)
    if value is None or value == "":
        raise FileOutputError("file_missing", f"the third party answered without a file ({path} is empty)")
    if not isinstance(value, str):
        raise FileOutputError("file_unreadable", f"the third party sent a {what} that is not a text ({path})")
    return value


def _decode(encoded: str, source: str) -> Optional[bytes]:
    """Strict decoding: the alphabet of `source`, no whitespace; padding required in base64, optional in base64url."""
    if source == "base64":
        if not _BASE64.match(encoded) or len(encoded) % 4:
            return None
        padded = encoded
    else:
        if not _BASE64URL.match(encoded) or ("=" in encoded and len(encoded) % 4) or len(encoded) % 4 == 1:
            return None
        padded = encoded + "=" * (-len(encoded) % 4)
    try:
        return base64.b64decode(padded, altchars=b"-_" if source == "base64url" else None, validate=True)
    except (binascii.Error, ValueError):
        return None


def _bare(session: requests.Session, address: str) -> requests.Session:
    """A session without the client's authentication, headers or cookies, on the client's transport (its adapter); it
    reads nothing from the environment (proxies, `.netrc`). Never closed: the adapter belongs to the client."""
    bare = requests.Session()
    bare.trust_env = False
    bare.mount("https://", session.get_adapter(address))
    return bare


def _same_origin(address: str, base_url: str) -> bool:
    """Same scheme, host and port (the default port of the scheme when absent)."""
    try:
        one, other = urlsplit(address), urlsplit(base_url)
        ports = (one.port or DEFAULT_PORTS.get(one.scheme.lower()), other.port or DEFAULT_PORTS.get(other.scheme.lower()))
    except ValueError:
        return False
    return (one.scheme.lower() == other.scheme.lower() and bool(one.hostname)
            and one.hostname == other.hostname and ports[0] == ports[1])


# --- Name and type -------------------------------------------------------------------------------------------------


def _name(file: dict, args: Mapping[str, Any], headers: Optional[Mapping[str, str]], data: Any) -> tuple[str, str]:
    """The first name whose extension is declared: the header, the field, then the template, which always gives one."""
    naming, types = file["name"], file["types"]
    candidates: list[str] = []
    if "header" in naming and headers is not None:
        value = headers.get(naming["header"])
        if value:
            candidates += _disposition_names(value) if naming["header"].lower() == "content-disposition" else [value]
    if "path" in naming and data is not None:
        value = value_at(data, naming["path"])
        if isinstance(value, str):
            candidates.append(value)
    candidates.append(_fill(naming["template"], args))
    for candidate in candidates:
        name = _clean(candidate)
        if name is not None and _extension(name) in types:
            return name, _extension(name)
    raise ValueError(f"the name template {naming['template']!r} does not end with a declared extension")


def _mime(file: dict, extension: str, announced: Optional[str]) -> str:
    """The type of the kept file, the first of its extension; an announced type outside it, not generic, refuses."""
    types = file["types"][extension]
    announced_type = (announced or "").split(";", 1)[0].strip().lower()
    if announced_type and announced_type not in types and announced_type not in GENERIC_TYPES:
        raise FileOutputError("file_type_refused", f"the third party sent {announced_type} instead of the file (.{extension})")
    return types[0]


def _disposition_names(value: str) -> list[str]:
    """The names of a `Content-Disposition` (RFC 6266): `filename*` (RFC 8187, UTF-8 or ISO-8859-1), then `filename`."""
    star = plain = None
    for match in _DISPOSITION_PARAMETER.finditer(value):
        key, raw = match.group(1).lower(), match.group(2).strip()
        if raw.startswith('"'):
            raw = re.sub(r"\\(.)", r"\1", raw[1:-1])
        if key == "filename*" and star is None:
            star = _extended(raw)
        elif key == "filename" and plain is None:
            plain = raw
    return [name for name in (star, plain) if name]


def _extended(raw: str) -> Optional[str]:
    match = _EXTENDED_VALUE.match(raw)
    if match is None or match.group(1).lower() not in ("utf-8", "iso-8859-1"):
        return None
    try:
        return unquote(match.group(2), encoding=match.group(1).lower(), errors="strict")
    except (UnicodeDecodeError, LookupError):
        return None


def _fill(template: str, args: Mapping[str, Any]) -> str:
    return _TEMPLATE_ARGUMENT.sub(lambda m: _text(args[m.group(1)]), template)


def _text(value: Any) -> str:
    """An argument as the host package writes it in a name (`String(value)` in JavaScript)."""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, float) and value.is_integer():
        return str(int(value))
    return str(value)


def _clean(name: str) -> Optional[str]:
    """The last segment, without control characters, 255 characters at most (its extension kept); `None` if nothing
    usable remains."""
    name = "".join(c for c in name if unicodedata.category(c) != "Cc")
    name = name.replace("\\", "/").rsplit("/", 1)[-1].strip()
    if name in ("", ".", ".."):
        return None
    if len(name) > NAME_LENGTH:
        stem, dot, extension = name.rpartition(".")
        name = stem[: NAME_LENGTH - len(extension) - 1] + dot + extension if dot and len(extension) <= 16 else name[:NAME_LENGTH]
    return name


def _extension(name: str) -> str:
    stem, dot, extension = name.rpartition(".")
    return extension.lower() if dot else ""
