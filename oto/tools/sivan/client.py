"""Sivan External API client — staff scheduling and workforce data (read-only).

External API (`https://api2.sivan.io`, routes under `/api/external`),
authenticated by the **`X-Api-Key`** header (the same value is also accepted as
`Authorization: Bearer <key>`). The key is issued per **company group** and
scopes every call to that group; it is read-only. One method = one endpoint;
responses are returned as-is, the client invents no semantics.

Scope: the whole external surface — companies (with their salaries, contracts
and localisations), salaries (with optional hour/absence counters), planned
calendar events, time-clock (badged) events, absences and timesheet aggregates.

What the caller needs to know, and cannot guess:

- **The key is a GROUP key, not a person's.** Every call returns the data of the
  whole company group attached to the key; `companies_ids` / `salaries_ids`
  narrow the result and are applied BEFORE generation, which matters on large
  groups (pass them to keep events/timesheets requests light).

- ⚠️ **A period is capped at 31 days (inclusive)** on `list_events`,
  `list_badged_events` and `list_timesheets`. For a longer range, split into
  successive windows and concatenate. `start`/`end` are dates or ISO-8601
  date-times; the API normalizes them to start/end of day.

- **`list_badged_events` needs the time-clock module** enabled on the group:
  without it the API answers 400 "Time clock module is not enabled".

- **Durations are in seconds** across timesheets and counters (`workingTime`,
  `counter`, `finalCounter`…). Week-level and root objects may carry extra
  numeric aggregates (overtime, paid vacation, night time…) beyond the
  documented fields: they are returned untouched.

- **`list_absences` returns PENDING, ACCEPTED and REFUSED** absences overlapping
  the period by default; pass `status` to restrict.

Requires: requests
"""
from __future__ import annotations

import time
from datetime import datetime
from typing import Any, Dict, List, Optional, Sequence

import requests

from ..common import raise_for_upstream
from ..common.credentials import require
from ..http.client import refuse_redirect

# (connect, read) — never an unbounded wait.
HTTP_TIMEOUT = (10, 60)

BASE_URL = "https://api2.sivan.io"
EXTERNAL_PREFIX = "/api/external"

#: A window is capped at this many days (inclusive) by the API.
MAX_PERIOD_DAYS = 31

#: Absence statuses accepted by `list_absences` (default: all three).
ABSENCE_STATUSES = ("PENDING", "ACCEPTED", "REFUSED")

# The external routes are read-only and idempotent (they generate nothing), so
# a 429/5xx is safe to replay.
RETRY_STATUSES = frozenset({429, 500, 502, 503, 504})
MAX_ATTEMPTS = 3


class SivanClient:
    """Sivan External API client (https://api2.sivan.io), `X-Api-Key` auth."""

    BASE_URL = BASE_URL

    def __init__(self, api_key: Optional[str] = None):
        """
        Args:
            api_key: Sivan company-group API key, passed by the consumer.
                Generated by a group administrator in Sivan, under the group's
                API-key settings.
        """
        self.api_key = require(api_key, "SIVAN_API_KEY")
        self.session = requests.Session()
        self.session.headers.update({
            "X-Api-Key": self.api_key,
            "Accept": "application/json",
        })

    # --- validation ---------------------------------------------------------

    @staticmethod
    def _parse_day(name: str, value: Any) -> datetime:
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"`{name}` must be a non-empty date or ISO-8601 string.")
        text = value.strip()
        try:
            return datetime.fromisoformat(text.replace("Z", "+00:00"))
        except ValueError:
            raise ValueError(
                f"`{name}`: {value!r} is not a date or ISO-8601 date-time "
                "(e.g. 2026-01-01 or 2026-01-01T13:00:00+01:00).")

    @classmethod
    def _period(cls, start: Any, end: Any, *,
                max_days: Optional[int] = MAX_PERIOD_DAYS) -> Dict[str, str]:
        """Validate a required {start, end} window and return it as sent.

        Both are required and `end` must not precede `start`. When `max_days` is
        set, the span must not exceed it (inclusive) — the same bound the API
        enforces, checked here to save a round-trip; `None` means no cap.
        """
        start_dt = cls._parse_day("start", start)
        end_dt = cls._parse_day("end", end)
        if end_dt < start_dt:
            raise ValueError("`end` must not be before `start`.")
        if max_days is not None and (end_dt - start_dt).days + 1 > max_days:
            raise ValueError(
                f"Period cannot exceed {max_days} days (inclusive); split a "
                "longer range into successive windows.")
        return {"start": start.strip(), "end": end.strip()}

    @staticmethod
    def _int_ids(name: str, values: Optional[Sequence[int]]) -> Optional[List[int]]:
        """A list of integer ids, or None. Empty is treated as absent (no filter)."""
        if values is None:
            return None
        if isinstance(values, (str, bytes)) or not isinstance(values, Sequence):
            raise ValueError(f"`{name}` must be a list of integer ids.")
        out: List[int] = []
        for v in values:
            if not isinstance(v, int) or isinstance(v, bool):
                raise ValueError(f"`{name}`: each id must be an integer; got {v!r}.")
            out.append(v)
        return out or None

    @classmethod
    def _statuses(cls, values: Optional[Sequence[str]]) -> Optional[List[str]]:
        if values is None:
            return None
        if isinstance(values, str):
            values = [values]
        out: List[str] = []
        for v in values:
            if v not in ABSENCE_STATUSES:
                raise ValueError(
                    f"`status`: {v!r} is not one of "
                    + ", ".join(ABSENCE_STATUSES) + ".")
            out.append(v)
        return out or None

    # --- transport ----------------------------------------------------------

    def _post(self, path: str, body: Optional[Dict[str, Any]] = None) -> Any:
        """POST a JSON body to an external route, with retry on 429/5xx (reads
        are idempotent). The key rides in a custom header, so redirects are
        refused before any retry (`requests` would keep the header cross-host)."""
        payload = {k: v for k, v in (body or {}).items() if v is not None}
        url = f"{self.BASE_URL}{EXTERNAL_PREFIX}{path}"
        last = None
        for attempt in range(MAX_ATTEMPTS):
            last = self.session.request(
                "POST", url, json=payload, timeout=HTTP_TIMEOUT,
                allow_redirects=False)
            refuse_redirect(last)
            if last.status_code not in RETRY_STATUSES or attempt == MAX_ATTEMPTS - 1:
                break
            time.sleep(float(2 ** attempt))
        raise_for_upstream(last, service="sivan")
        return last.json() if last.content else []

    # --- probe --------------------------------------------------------------

    def probe(self) -> Any:
        """Check that the key authenticates, for the cost of one call (401 if wrong)."""
        return self.list_companies()

    # --- reads ---------------------------------------------------------------

    def list_companies(self) -> Any:
        """POST /api/external/companies — activated companies of the group.

        Each company carries its salaries (with contracts), localisations and
        opening hours.
        """
        return self._post("/companies", {})

    def list_salaries(self, with_counter: Optional[bool] = None,
                      with_absences_counter: Optional[bool] = None) -> Any:
        """POST /api/external/salaries — the group's salaries.

        `with_counter` adds each salary's hour counter (seconds) for the current
        ISO week/year; `with_absences_counter` adds the absences counter object.
        """
        return self._post("/salaries", {
            "withCounter": with_counter,
            "withAbsencesCounter": with_absences_counter,
        })

    def list_events(self, start: str, end: str, *,
                   with_absence_type: Optional[bool] = None,
                   companies_ids: Optional[Sequence[int]] = None,
                   salaries_ids: Optional[Sequence[int]] = None) -> Any:
        """POST /api/external/events — planned calendar events over a window.

        Returned grouped by company then salary. Period capped at 31 days.
        `with_absence_type` adds `absenceType` on each event (null when not an
        absence). `companies_ids`/`salaries_ids` narrow BEFORE generation.
        """
        body = self._period(start, end)
        body["withAbsenceType"] = with_absence_type
        body["companiesIds"] = self._int_ids("companies_ids", companies_ids)
        body["salariesIds"] = self._int_ids("salaries_ids", salaries_ids)
        return self._post("/events", body)

    def list_badged_events(self, start: str, end: str, *,
                          companies_ids: Optional[Sequence[int]] = None,
                          salaries_ids: Optional[Sequence[int]] = None) -> Any:
        """POST /api/external/badged-events — time-clock (badged) events.

        Requires the time-clock module on the group (400 otherwise). Grouped by
        company then salary; period capped at 31 days. `companies_ids`/
        `salaries_ids` narrow BEFORE generation.
        """
        body = self._period(start, end)
        body["companiesIds"] = self._int_ids("companies_ids", companies_ids)
        body["salariesIds"] = self._int_ids("salaries_ids", salaries_ids)
        return self._post("/badged-events", body)

    def list_absences(self, start: str, end: str, *,
                     status: Optional[Sequence[str]] = None,
                     salaries_ids: Optional[Sequence[int]] = None) -> Any:
        """POST /api/external/absences — absences overlapping the window.

        Flat list. Defaults to PENDING, ACCEPTED and REFUSED; `status` restricts
        to a subset. `salaries_ids` narrows to listed salaries.
        """
        body = self._period(start, end, max_days=None)
        body["status"] = self._statuses(status)
        body["salariesIds"] = self._int_ids("salaries_ids", salaries_ids)
        return self._post("/absences", body)

    @staticmethod
    def _strip_days(timesheets: Any) -> Any:
        """Drop each week's per-day breakdown, keeping the weekly aggregates.

        The `days` array (eventsPlanned/eventsDone per day) is by far the
        heaviest part of a timesheet; for payroll only the weekly totals matter
        (workingTime, accountedWorkingTime and any overtime / paid-leave
        aggregates carried at week level). Mutates and returns the parsed
        response in place; nothing else is altered.
        """
        if not isinstance(timesheets, list):
            return timesheets
        for sheet in timesheets:
            if not isinstance(sheet, dict):
                continue
            for week in sheet.get("weeks") or []:
                if isinstance(week, dict):
                    week.pop("days", None)
        return timesheets

    def list_timesheets(self, start: str, end: str, *,
                        salaries_ids: Optional[Sequence[int]] = None) -> Any:
        """POST /api/external/timesheets — timesheet aggregates per salary/contract.

        Weekly totals and daily planned/done events over the window; root and
        week objects may carry extra numeric aggregates (overtime, paid vacation,
        night time…). Period capped at 31 days. `salaries_ids` narrows to listed
        salaries.
        """
        body = self._period(start, end)
        body["salariesIds"] = self._int_ids("salaries_ids", salaries_ids)
        return self._post("/timesheets", body)

    def list_timesheets_summary(self, start: str, end: str, *,
                               salaries_ids: Optional[Sequence[int]] = None) -> Any:
        """POST /api/external/timesheets, weekly totals only (no per-day detail).

        Same call as `list_timesheets`, then drops each week's `days` array
        (eventsPlanned/eventsDone) — far smaller, the shape payroll needs across
        many contracts. Weekly aggregates (contractWorkingTime,
        accountedWorkingTime, overtime…) are kept untouched; a missing field
        stays missing (nothing is inferred). Period capped at 31 days.
        """
        return self._strip_days(self.list_timesheets(start, end, salaries_ids=salaries_ids))


